// Ícones de ITEM, em grade de 32x32.
//
// POR QUE 32 E NÃO 16
// Os ícones de interface (ação, reação, correr, esquivar) são glifos: uma
// forma abstrata que 16x16 carrega bem. Arma e armadura não são glifos — são
// OBJETOS, e um objeto precisa de punho, guarda, pomo e lâmina para ser
// reconhecido. Em 16x16 a espada tinha lâmina de 2 px, guarda de uma linha e
// nenhum pomo: lia como um prego com um traço atravessado.
//
// 32x32 renderizado a 1 px por pixel ocupa os mesmos 32 px de tela que a
// grade de 16 ocupava a 2 px por pixel. Nenhuma caixa da interface mudou de
// tamanho — o que mudou foi o orçamento de desenho, que quadruplicou.
//
// A GRAMÁTICA, lida das referências de pixel art:
//
//   1. CONTORNO FECHA A PEÇA. Todo objeto é cercado por `e`, o escuro duro.
//      Sem contorno, metal claro sobre pergaminho claro some — e a interface
//      agora é pergaminho.
//   2. TRÊS VALORES NO METAL, nesta ordem da esquerda para a direita:
//      `1` fio claro, `2` corpo, `3` sombra. A luz vem de cima e da esquerda,
//      a mesma direção do pintor de sprites. Uma lâmina de um valor só é uma
//      barra; é o degrau que faz o olho ver um gume.
//   3. O PUNHO SÃO TRÊS PEÇAS: guarda larga, cabo enrolado, pomo redondo.
//      Nenhuma delas é decoração — é o conjunto que diz "isto se segura".
//      A guarda tem de ser visivelmente mais larga que a lâmina, ou a arma
//      lê como estaca.
//   4. O CABO É ENROLADO, em faixas alternadas de couro claro e escuro. Duas
//      linhas bastam, e é o que mais barato distingue arma de ferramenta.
//   5. UM ACENTO POR ARMA: ouro na guarda, gema no pomo, fita no cabo. Um
//      só. Dois acentos brigam e a peça vira bijuteria.
//
// COMO CORRIGIR
// Cada ícone é texto. Para mexer num, olhe para ele e troque caracteres —
// era esse o motivo de a grade existir em vez de chamadas de fillRect, e
// continua sendo. Toda linha tem de ter exatamente 32 caracteres; o teste em
// `src/dev/icones.js` recusa o arquivo se alguma não tiver.

